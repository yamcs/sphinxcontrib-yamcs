from docutils.statemachine import StringList
from sphinx.directives.other import TocTree


class ApiTocTreeDirective(TocTree):
    """
    A toctree listing the top level of autogenerated API documents
    (service indexes, or methods when only one service is documented).

    Accepts the same options as toctree. Combine with
    ``yamcs_api_index = False`` to have the generated documents appear
    directly in the including document, rather than nested under a
    generated index.
    """

    has_content = False

    def run(self):
        app = self.env.app
        if not app.config.yamcs_api_protobin:
            raise self.error(
                f"{self.name} requires yamcs_api_protobin to be configured"
            )

        _api_toctree_docs(self.env).add(self.env.docname)

        # Absolute docnames, so that the directive can be used from any document
        self.content = StringList(
            ["/" + link for link in app.yamcs_api_toc_links],
            source=self.env.docname,
        )
        return super().run()


def _api_toctree_docs(env):
    if not hasattr(env, "yamcs_api_toctree_docs"):
        env.yamcs_api_toctree_docs = set()
    return env.yamcs_api_toctree_docs


def env_before_read_docs(app, env, docnames):
    _api_toctree_docs(env)


def env_get_outdated(app, env, added, changed, removed):
    """
    Documents using the directive must be reread when the generated
    links change, even if the documents themselves did not.
    """
    docs = _api_toctree_docs(env)
    links = getattr(app, "yamcs_api_toc_links", [])
    outdated = []
    if getattr(env, "yamcs_api_toc_links", None) != links:
        outdated = list(docs)
    env.yamcs_api_toc_links = links
    return outdated


def env_purge_doc(app, env, docname):
    _api_toctree_docs(env).discard(docname)


def env_merge_info(app, env, docnames, other):
    _api_toctree_docs(env).update(_api_toctree_docs(other))
