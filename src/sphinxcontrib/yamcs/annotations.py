"""
Yamcs API annotations (``yamcs.api.route``, ``yamcs.api.label``, ...).

These are loaded into a private descriptor pool, together with the
``FileDescriptorSet`` class used to parse the API protobin. They are
deliberately kept out of protobuf's default pool: other packages in the
same process (yamcs-client, when documented with autodoc) register their
own copy of the Yamcs API annotations there, and protobuf rejects
duplicate symbols.
"""

from pathlib import Path
from typing import cast

from google.protobuf import descriptor_pb2, descriptor_pool, message_factory

__all__ = [
    "FileDescriptorSet",
    "field_behavior",
    "label",
    "markdown",
    "route",
    "websocket",
]

_pool = descriptor_pool.DescriptorPool()
_pool.AddSerializedFile(descriptor_pb2.DESCRIPTOR.serialized_pb)

# Generated by update-proto.sh
_data = Path(__file__).with_name("annotations.binpb").read_bytes()
for _file in descriptor_pb2.FileDescriptorSet.FromString(_data).file:
    _pool.AddSerializedFile(_file.SerializeToString())

# Same shape as descriptor_pb2.FileDescriptorSet, but bound to the private pool
FileDescriptorSet = cast(
    "type[descriptor_pb2.FileDescriptorSet]",
    message_factory.GetMessageClass(
        _pool.FindMessageTypeByName("google.protobuf.FileDescriptorSet")
    ),
)

label = _pool.FindExtensionByName("yamcs.api.label")
markdown = _pool.FindExtensionByName("yamcs.api.markdown")
route = _pool.FindExtensionByName("yamcs.api.route")
websocket = _pool.FindExtensionByName("yamcs.api.websocket")
field_behavior = _pool.FindExtensionByName("yamcs.api.field_behavior")
